const mongoose = require("mongoose");

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
      minlength: 3
    },
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true
    },
    password: {
      type: String,
      required: true // stocké hashé (bcrypt), jamais en clair
    }
  },
  { timestamps: true }
);

module.exports = mongoose.model("User", userSchema);
